// ── pshadow fp shader ─────────────────────────────────────────────────────────
// GL2 ref: code/renderergl2/glsl/pshadow_fp.glsl
// Implements USE_PCF + USE_DISCARD variant (the default compile in tr_glsl.cpp).
// u_ShadowMap is a depth2d<float> texture sampled as a regular texture (not comparison);
// occluder presence test: sample.r != 1.0 (depth < 1.0 means something rendered there).
static const char *s_pshadow_fp =
"// GL2 ref: code/renderergl2/glsl/pshadow_fp.glsl (USE_PCF + USE_DISCARD)\n"
"\n"
"#include <metal_stdlib>\n"
"using namespace metal;\n"
"\n"
"struct PshadowUniforms {\n"
"    float4x4 u_ModelViewProjectionMatrix; // offset   0  (64 B)\n"
"    float4   u_LightOrigin;              // offset  64  (16 B)\n"
"    float4   u_LightForward;             // offset  80  (16 B)\n"
"    float4   u_LightRight;               // offset  96  (16 B)\n"
"    float4   u_LightUp;                  // offset 112  (16 B)\n"
"    float    u_LightRadius;              // offset 128  ( 4 B)\n"
"    int      u_AlphaTest;                // offset 132  ( 4 B)\n"
"    float    _pad[6];                    // offset 136  (24 B)\n"
"};\n"
"\n"
"struct PshadowV2F {\n"
"    float4 position    [[position]];\n"
"    float3 var_Position;\n"
"    float3 var_Normal;\n"
"};\n"
"\n"
"fragment float4 pshadow_frag(\n"
"    PshadowV2F in                            [[stage_in]],\n"
"    constant PshadowUniforms& u              [[buffer(0)]],\n"
"    depth2d<float> u_ShadowMap               [[texture(0)]],\n"
"    sampler u_ShadowMapSampler               [[sampler(0)]])\n"
"{\n"
"    // GL2 ref: pshadow_fp.glsl:14-15\n"
"    float3 lightToPos = in.var_Position - u.u_LightOrigin.xyz;\n"
"\n"
"    // Project onto shadow-map axes — GL2 ref: pshadow_fp.glsl:16-17\n"
"    float2 st = float2(-dot(u.u_LightRight.xyz, lightToPos),\n"
"                        dot(u.u_LightUp.xyz, lightToPos));\n"
"\n"
"    float fade = length(st);\n"
"\n"
"    // USE_DISCARD: early-out if outside shadow frustum — GL2 ref: pshadow_fp.glsl:22\n"
"    if (fade >= 1.0) discard_fragment();\n"
"\n"
"    // GL2 ref: pshadow_fp.glsl:25\n"
"    fade = clamp(8.0 - fade * 8.0, 0.0, 1.0);\n"
"\n"
"    // Map to [0,1] UV — GL2 ref: pshadow_fp.glsl:27\n"
"    st = st * 0.5 + 0.5;\n"
"\n"
"    // PARITY-SEAM(Metal-device): the shadowfill depth map is rasterized through the\n"
"    // global Metal viewport Y-flip (tr_metal_device.cpp: vp.originY = dh-(vy+vh)), so it\n"
"    // is stored vertically mirrored vs the GL FBO origin. GL2 samples with no flip; here\n"
"    // we flip V to compensate. Without this, spinning occluders cast shadows that rotate\n"
"    // in the opposite direction (vertical mirror reverses chirality).\n"
"    st.y = 1.0 - st.y;\n"
"\n"
"    // Intensity from distance falloff — GL2 ref: pshadow_fp.glsl:30-31\n"
"    float intensity = clamp((1.0 - dot(lightToPos, lightToPos) /\n"
"                            (u.u_LightRadius * u.u_LightRadius)) * 2.0, 0.0, 1.0);\n"
"\n"
"    // USE_DISCARD: directional culling — GL2 ref: pshadow_fp.glsl:34-37\n"
"    if (dot(u.u_LightForward.xyz, lightToPos) <= 0.0) discard_fragment();\n"
"    if (dot(in.var_Normal, lightToPos) > 0.0) discard_fragment();\n"
"\n"
"    intensity *= fade;\n"
"\n"
"    // USE_PCF: 4-tap PCF — GL2 ref: pshadow_fp.glsl:48-55\n"
"    float texelSize = 1.0 / 512.0;\n"
"    float part = 0.0;\n"
"    part += (u_ShadowMap.sample(u_ShadowMapSampler, st + float2(-texelSize, -texelSize)) != 1.0) ? 1.0 : 0.0;\n"
"    part += (u_ShadowMap.sample(u_ShadowMapSampler, st + float2( texelSize, -texelSize)) != 1.0) ? 1.0 : 0.0;\n"
"    part += (u_ShadowMap.sample(u_ShadowMapSampler, st + float2(-texelSize,  texelSize)) != 1.0) ? 1.0 : 0.0;\n"
"    part += (u_ShadowMap.sample(u_ShadowMapSampler, st + float2( texelSize,  texelSize)) != 1.0) ? 1.0 : 0.0;\n"
"\n"
"    if (part <= 0.0) discard_fragment();\n"
"\n"
"    // GL2 ref: pshadow_fp.glsl:57\n"
"    intensity *= part * 0.25;\n"
"\n"
"    // GL2 ref: pshadow_fp.glsl:63-64\n"
"    return float4(0.0, 0.0, 0.0, clamp(intensity, 0.0, 0.75));\n"
"}\n";

