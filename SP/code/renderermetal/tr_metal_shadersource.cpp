"    float depth = getLinearDepth(u_ScreenDepthMap, in.var_DepthTex, u.u_ViewInfo.x);\n"
"\n"
"    // GL2 ref: shadowmask_fp.glsl:93 — biasPos = vec4(u_ViewOrigin + var_ViewDir*(depth-0.5/zFarDivZNear), 1)\n"
"    float4 biasPos = float4(\n"
"        u.u_ViewOrigin.xyz + in.var_ViewDir * (depth - 0.5f / u.u_ViewInfo.x),\n"
"        1.0f);\n"
"\n"
"    // GL2 ref: shadowmask_fp.glsl:95 — shadowpos = u_ShadowMvp * biasPos\n"
"    float4 shadowpos = u.u_ShadowMvp * biasPos;\n"
"\n"
"    float result;\n"
"\n"
"    // GL2 ref: shadowmask_fp.glsl:97-99 — sky/far-plane early-out\n"
"    if (depth >= 0.999f)\n"
"    {\n"
"        result = 1.0f;\n"
"    }\n"
"    // GL2 ref: shadowmask_fp.glsl:100 (USE_SHADOW_CASCADE) — cascade 0 clip-space bounds check\n"
"    // GLSL: all(lessThan(abs(xyz), vec3(abs(w)))) -> MSL: all(abs(xyz) < float3(abs(w)))\n"
"    else if (all(abs(shadowpos.xyz) < float3(abs(shadowpos.w))))\n"
"    {\n"
"        // GL2 ref: shadowmask_fp.glsl:102 — project to [0,1] UV + reference depth\n"
"        shadowpos.xyz = shadowpos.xyz * (0.5f / shadowpos.w) + float3(0.5f);\n"
"        // PARITY-SEAM(Z-remap): GL2 ortho MVP produces Z NDC in [-1,1]; the * 0.5 + 0.5\n"
"        // above converts it to [0,1] matching GL depth buffer storage. Metal Depth32Float\n"
"        // also stores [0,1]. If sun shadow captures use a Metal-remapped MVP (Z already\n"
"        // in [0,1] before the * 0.5 + 0.5), the Z component will be wrong — remove\n"
"        // the Z portion of the remap in E6-5 if self-shadowing artifacts appear.\n"
"        // GL2 ref: shadowmask_fp.glsl:102\n"
"        //\n"
"        // PARITY-SEAM(V-flip): sun shadow depth maps are rasterized through the Metal\n"
"        // viewport Y-flip (tr_metal_device.cpp) and stored vertically mirrored vs GL.\n"
"        // Flip V (shadowpos.y) to compensate — same fix as s_pshadow_fp (E5).\n"
"        // GL2 ref: shadowmask_fp.glsl:103 (no flip in GL2; Metal-specific)\n"
"        shadowpos.y = 1.0f - shadowpos.y;\n"
"        result = PCF(u_ShadowMap, shadowpos.xy, shadowpos.z,\n"
"                     u.u_ShadowMapSize, in.var_DepthTex);\n"
"    }\n"
"    // GL2 ref: shadowmask_fp.glsl:106-129 (USE_SHADOW_CASCADE) — cascades 1-3\n"
"    else\n"
"    {\n"
"        shadowpos = u.u_ShadowMvp2 * biasPos;  // GL2 ref: shadowmask_fp.glsl:108\n"
"        if (all(abs(shadowpos.xyz) < float3(abs(shadowpos.w))))\n"
"        {\n"
"            shadowpos.xyz = shadowpos.xyz * (0.5f / shadowpos.w) + float3(0.5f);\n"
"            shadowpos.y = 1.0f - shadowpos.y;  // PARITY-SEAM(V-flip)\n"
"            result = PCF(u_ShadowMap2, shadowpos.xy, shadowpos.z,\n"
"                         u.u_ShadowMapSize, in.var_DepthTex);\n"
"        }\n"
"        else\n"
"        {\n"
"            shadowpos = u.u_ShadowMvp3 * biasPos;  // GL2 ref: shadowmask_fp.glsl:116\n"
"            if (all(abs(shadowpos.xyz) < float3(abs(shadowpos.w))))\n"
"            {\n"
"                shadowpos.xyz = shadowpos.xyz * (0.5f / shadowpos.w) + float3(0.5f);\n"
"                shadowpos.y = 1.0f - shadowpos.y;  // PARITY-SEAM(V-flip)\n"
"                result = PCF(u_ShadowMap3, shadowpos.xy, shadowpos.z,\n"
"                             u.u_ShadowMapSize, in.var_DepthTex);\n"
"            }\n"
"            else\n"
"            {\n"
"                // GL2 ref: shadowmask_fp.glsl:124-127 — cascade 3 fallback (no bounds check)\n"
"                shadowpos = u.u_ShadowMvp4 * biasPos;\n"
"                shadowpos.xyz = shadowpos.xyz * (0.5f / shadowpos.w) + float3(0.5f);\n"
"                shadowpos.y = 1.0f - shadowpos.y;  // PARITY-SEAM(V-flip)\n"
"                result = PCF(u_ShadowMap4, shadowpos.xy, shadowpos.z,\n"
"                             u.u_ShadowMapSize, in.var_DepthTex);\n"
"            }\n"
"        }\n"
"    }\n"
"\n"
"    // GL2 ref: shadowmask_fp.glsl:131 — gl_FragColor = vec4(vec3(result), 1.0)\n"
"    return float4(result, result, result, 1.0f);\n"
"}\n";

// ── depthblur vp shader ───────────────────────────────────────────────────────
// GL2 ref: code/renderergl2/glsl/depthblur_vp.glsl
// Program: "depthBlur" (GL2 ref: tr_glsl.c:1514) — r_shadowBlur two-pass separable blur.
//
// BINDING CONTRACT (vertex stage) — PARITY-SEAM(Metal-blit), same pattern as shadowmask_vert:
//   [[vertex_id]]  — uint vertexID, indexes positions[] and texcoords[] (no stage_in/vertex descriptor)
//   [[buffer(1)]]  — DepthBlurUniforms (16 B)
//   [[buffer(2)]]  — const device float4* positions  (NDC quad, z=0 w=1; host: setVertexBytes(...,2))
//   [[buffer(3)]]  — const device float2* texcoords  (UV quad; host: setVertexBytes(...,3))
//   GL2 ref: RB_InstantQuad2 vertex stream → Metal pre-built NDC quad via setVertexBytes
// Entry points: depthBlur_vert / depthBlur_frag
//
// DepthBlurUniforms byte layout (16 B = 1 × 16) — Hudson MUST match exactly:
//   offset  0  (16 B) float4 u_ViewInfo — x=zfar/znear, y=zfar, z=1/width, w=1/height
//                                         (GL2 ref: depthblur_vp.glsl:4)
//
// PARITY-SEAM (renderDepthImage-direct, decision vasquez-depthblur-binding.md):
//   GL2 uses tr.hdrDepthImage — a copy of renderDepthImage made via FBO blit, required
//   because GL cannot reliably sample the active depth attachment. Metal samples
//   tr.renderDepthImage DIRECTLY as depth2d<float> (full-res, sampleable, populated by
//   the depth prepass at the point the blur runs). The hdrDepth copy is eliminated.
//
// Compile-time permutations — Metal pipeline compiler prepends extradefines before
// newLibraryWithSource; pipeline cache keys on the define string (GL2 ref: tr_glsl.c:1074):
//   i=0: #define USE_HORIZONTAL_BLUR + #define USE_DEPTH  (r_shadowBlur pass 1)
//   i=1: #define USE_VERTICAL_BLUR   + #define USE_DEPTH  (r_shadowBlur pass 2)
//   i=2: #define USE_HORIZONTAL_BLUR                      (no depth gate)
//   i=3: #define USE_VERTICAL_BLUR                        (no depth gate)
//   (GL2 ref: tr_glsl.c:1507-1511)
//   USE_GAUSS: commented out in GL2 at depthblur_fp.glsl:31 — never defined;
//   non-Gauss (total=1.0) path is always taken. USE_GAUSS path omitted from MSL.
static const char *s_depthblur_vp =
"// GL2 ref: code/renderergl2/glsl/depthblur_vp.glsl\n"
"// Program: \"depthBlur\" (GL2 ref: tr_glsl.c:1514)\n"
"\n"
"#include <metal_stdlib>\n"
"using namespace metal;\n"
"\n"
"// ── Uniform struct — must byte-match MetalDepthBlurUniforms (16 B).\n"
"// BINDING CONTRACT (vertex): [[buffer(1)]]=DepthBlurUniforms, [[buffer(2)]]=positions (float4*),\n"
"//   [[buffer(3)]]=texcoords (float2*); indexed by [[vertex_id]]. No stage_in / vertex descriptor.\n"
"//   PARITY-SEAM(Metal-blit): GL2 RB_InstantQuad2 vertex stream → Metal setVertexBytes NDC quad.\n"
"struct DepthBlurUniforms {\n"
"    float4 u_ViewInfo; // offset  0  (16 B): x=zfar/znear, y=zfar, z=1/width, w=1/height\n"
"                       // GL2 ref: depthblur_vp.glsl:4 — uniform vec4 u_ViewInfo\n"
"                       // total: 16 B\n"
"};\n"
"static_assert(sizeof(DepthBlurUniforms) == 16,\n"
"    \"DepthBlurUniforms must mirror MetalDepthBlurUniforms in host code\");\n"
"\n"
"// GL2 ref: depthblur_vp.glsl:6 — varying vec2 var_ScreenTex\n"
"struct DepthBlurV2F {\n"
"    float4 position      [[position]];\n"
"    float2 var_ScreenTex;  // GL2 ref: depthblur_vp.glsl:6\n"
"};\n"
"\n"
"vertex DepthBlurV2F depthBlur_vert(\n"
"    uint vertexID                          [[vertex_id]],\n"
"    constant DepthBlurUniforms& u          [[buffer(1)]],\n"
"    const device float4* positions         [[buffer(2)]],\n"
"    const device float2* texcoords         [[buffer(3)]])\n"
"{\n"
"    DepthBlurV2F out;\n"
"    // PARITY-SEAM(Metal-blit): GL2 uses attr_Position from RB_InstantQuad2 vertex attrib;\n"
"    // Metal host supplies pre-built NDC positions (z=0, w=1) via setVertexBytes [[buffer(2)]].\n"
"    out.position = float4(positions[vertexID].xyz, 1.0);            // GL2 ref: depthblur_vp.glsl:9 (attr_Position passthrough)\n"
"    float2 wh = float2(1.0) / u.u_ViewInfo.zw - float2(1.0);        // GL2 ref: depthblur_vp.glsl:10\n"
"    out.var_ScreenTex = (floor(texcoords[vertexID] * wh) + float2(0.5)) * u.u_ViewInfo.zw;  // GL2 ref: depthblur_vp.glsl:11\n"
"    return out;\n"
"}\n";

// ── depthblur fp shader ───────────────────────────────────────────────────────
// GL2 ref: code/renderergl2/glsl/depthblur_fp.glsl
// BINDING CONTRACT (fragment stage):
//   [[texture(0)]] — texture2d<float> u_ScreenImageMap (TB_COLORMAP=0; shadowmask/scratch color)
//   [[texture(1)]] — depth2d<float>   u_ScreenDepthMap (TB_LIGHTMAP=1; tr.renderDepthImage)
//   [[buffer(0)]]  — DepthBlurUniforms (16 B)
//   NO [[sampler(N)]] slots — all samplers are constexpr (self-contained).
//   Sampler: LINEAR clamp_to_edge for both imageMap and depthMap.
//     GL2 ref: u_ScreenImageMap bound GL_LINEAR (tr_glsl.c:1521); hdrDepthImage GL_LINEAR no-mip.
//     PARITY-SEAM: data source changes (no blit copy); filter behaviour is identical.
// Key GL2→MSL mappings:
//   dFdx/dFdy → dfdx/dfdy (valid in fragment; GL2 ref: depthblur_fp.glsl:50-51)
//   texture2D(map,uv).r on sampler2D → map.sample(s,uv) on depth2d<float> (returns float)
//   texture2D(map,uv)   on sampler2D → map.sample(s,uv) on texture2d<float> (returns float4)
//   float(bool_expr)    → float(bool_expr) — identical semantics (0.0/1.0)
//   GLSL mix → MSL mix (identical)
static const char *s_depthblur_fp =
"// GL2 ref: code/renderergl2/glsl/depthblur_fp.glsl\n"
"// Program: \"depthBlur\" (GL2 ref: tr_glsl.c:1514)\n"
"// Compile-time permutations (extradefines prepended by Metal pipeline compiler):\n"
"//   USE_HORIZONTAL_BLUR / USE_VERTICAL_BLUR — blur axis (GL2 ref: depthblur_fp.glsl:53-60)\n"
"//   USE_DEPTH — depth-aware sample rejection  (GL2 ref: depthblur_fp.glsl:49-52)\n"
"// USE_GAUSS: commented out in GL2 (depthblur_fp.glsl:31) — never defined; omitted from MSL.\n"
"// PARITY-SEAM (renderDepthImage-direct): u_ScreenDepthMap bound to tr.renderDepthImage\n"
"//   directly as depth2d<float>. GL2 used tr.hdrDepthImage (a blit copy). Filter: LINEAR.\n"
"\n"
"#include <metal_stdlib>\n"
"using namespace metal;\n"
"\n"
"// GL2 ref: depthblur_fp.glsl:26 — #define BLUR_SIZE 4\n"
"#define BLUR_SIZE 4\n"
"\n"
"// ── Uniform struct — must byte-match MetalDepthBlurUniforms (16 B).\n"
"// BINDING CONTRACT: fragment [[buffer(0)]].\n"
"struct DepthBlurUniforms {\n"
"    float4 u_ViewInfo; // offset  0  (16 B): x=zfar/znear, y=zfar, z=1/width, w=1/height\n"
"                       // GL2 ref: depthblur_fp.glsl:3 — uniform vec4 u_ViewInfo\n"
"                       // total: 16 B\n"
"};\n"
"static_assert(sizeof(DepthBlurUniforms) == 16,\n"
"    \"DepthBlurUniforms must mirror MetalDepthBlurUniforms in host code\");\n"
"\n"
"// GL2 ref: depthblur_vp.glsl:6 — varying vec2 var_ScreenTex\n"
"struct DepthBlurV2F {\n"
"    float4 position      [[position]];\n"
"    float2 var_ScreenTex;\n"
"};\n"
"\n"
"// GL2 ref: u_ScreenImageMap bound GL_LINEAR (tr_glsl.c:1521)\n"
"constexpr sampler s_imageSampler(filter::linear, address::clamp_to_edge);\n"
"// PARITY-SEAM (renderDepthImage-direct): GL2 hdrDepthImage was GL_LINEAR no-mip.\n"
"// Metal renderDepthImage has no mip chain at this pass; LINEAR clamp_to_edge matches.\n"
"constexpr sampler s_depthSampler(filter::linear, address::clamp_to_edge);\n"
"\n"
"// GL2 ref: depthblur_fp.glsl:35-39\n"
"// Returns linear (eye-space) depth from a Depth32Float sample.\n"
"// sampleZDivW in [0,1]; mix(zFarDivZNear,1,s) linearises the perspective projection.\n"
"static float getLinearDepth(\n"
"    depth2d<float> depthMap, float2 tex, float zFarDivZNear)\n"
"{\n"
"    float sampleZDivW = depthMap.sample(s_depthSampler, tex);\n"
"    // GL2 ref: depthblur_fp.glsl:38 — return 1.0 / mix(zFarDivZNear, 1.0, sampleZDivW)\n"
"    return 1.0f / mix(zFarDivZNear, 1.0f, sampleZDivW);\n"
"}\n"
"\n"
"// GL2 ref: depthblur_fp.glsl:41-98\n"
"// Separable 1D Gaussian blur with optional depth-aware sample rejection.\n"
"// BLUR_SIZE=4 → inner loop iterates j=1,2,3 (3 samples per side per pass; 2 passes).\n"
"// USE_GAUSS never defined — non-Gauss (total=1.0) path always taken.\n"
"static float4 depthGaussian1D(\n"
"    texture2d<float> imageMap,\n"
"    depth2d<float>   depthMap,\n"
"    float2 tex,\n"
"    float  zFarDivZNear,\n"
"    float  zFar,\n"
"    float2 scale)\n"
"{\n"
"    // GL2 ref: depthblur_fp.glsl:43-47 — gauss[] only used by USE_GAUSS path (omitted).\n"
"\n"
"#if defined(USE_DEPTH)\n"
"    // GL2 ref: depthblur_fp.glsl:49\n"
"    float  depthCenter = getLinearDepth(depthMap, tex, zFarDivZNear);\n"
"    // GL2 ref: depthblur_fp.glsl:50-51\n"
"    // dFdx/dFdy → MSL dfdx/dfdy (valid in fragment; GL2 ref: depthblur_fp.glsl:50)\n"
"    float2 slope = float2(dfdx(depthCenter), dfdy(depthCenter))\n"
"                 / float2(dfdx(tex.x), dfdy(tex.y));\n"
"    // GL2 ref: depthblur_fp.glsl:52 — scale /= clamp(zFarDivZNear*depthCenter/32.0, 1.0, 2.0)\n"
"    scale /= clamp(zFarDivZNear * depthCenter / 32.0f, 1.0f, 2.0f);\n"
"#endif\n"
"\n"
"#if defined(USE_HORIZONTAL_BLUR)\n"
"    // GL2 ref: depthblur_fp.glsl:55-56\n"
"    float2 direction = float2(scale.x * 2.0f, 0.0f);\n"
"    float2 nudge     = float2(0.0f, scale.y * 0.5f);\n"
"#else // USE_VERTICAL_BLUR\n"
"    // GL2 ref: depthblur_fp.glsl:58-59\n"
"    float2 direction = float2(0.0f, scale.y * 2.0f);\n"
"    float2 nudge     = float2(-scale.x * 0.5f, 0.0f);\n"
"#endif\n"
"\n"
"    // GL2 ref: depthblur_fp.glsl:62-64 — non-Gauss base sample (USE_GAUSS never defined)\n"
"    float4 result = imageMap.sample(s_imageSampler, tex);\n"
"    float  total  = 1.0f;\n"
"\n"
"    // GL2 ref: depthblur_fp.glsl:66\n"
"    float zLimit = 5.0f / zFar;\n"
"\n"
"    // GL2 ref: depthblur_fp.glsl:67-91 — two-direction loop (i flips direction each pass)\n"
"    for (int i = 0; i < 2; i++) {\n"
"        for (int j = 1; j < BLUR_SIZE; j++) {\n"
"            // GL2 ref: depthblur_fp.glsl:70\n"
"            float2 offset = direction * (float(j) - 0.25f) + nudge;\n"
"#if defined(USE_DEPTH)\n"
"            // GL2 ref: depthblur_fp.glsl:72-74\n"
"            float depthSample   = getLinearDepth(depthMap, tex + offset, zFarDivZNear);\n"
"            float depthExpected = depthCenter + dot(slope, offset);\n"
"            // GLSL float(bool) → MSL float(bool): identical 0.0/1.0 semantics\n"
"            float useSample     = float(abs(depthSample - depthExpected) < zLimit);\n"
"#else\n"
"            float useSample = 1.0f;\n"
"#endif\n"
"            // GL2 ref: depthblur_fp.glsl:81-82 — non-Gauss accumulate\n"
"            result += imageMap.sample(s_imageSampler, tex + offset) * useSample;\n"
"            total  += useSample;\n"
"            // GL2 ref: depthblur_fp.glsl:85 — nudge = -nudge\n"
"            nudge   = -nudge;\n"
"        }\n"
"        // GL2 ref: depthblur_fp.glsl:88-89 — flip direction and nudge for second pass\n"
"        direction = -direction;\n"
"        nudge     = -nudge;\n"
"    }\n"
"\n"
"    // GL2 ref: depthblur_fp.glsl:92 — return result / total\n"
"    return result / total;\n"
"}\n"
"\n"
"fragment float4 depthBlur_frag(\n"
"    DepthBlurV2F             in             [[stage_in]],\n"
"    texture2d<float>         u_ScreenImageMap [[texture(0)]],\n"
"    depth2d<float>           u_ScreenDepthMap [[texture(1)]],\n"
"    constant DepthBlurUniforms& u            [[buffer(0)]])\n"
"{\n"
"    // GL2 ref: depthblur_fp.glsl:100-102\n"
"    // gl_FragColor = depthGaussian1D(u_ScreenImageMap, u_ScreenDepthMap, var_ScreenTex,\n"
"    //                                u_ViewInfo.x, u_ViewInfo.y, u_ViewInfo.zw)\n"
"    return depthGaussian1D(\n"
"        u_ScreenImageMap, u_ScreenDepthMap,\n"
"        in.var_ScreenTex,\n"
"        u.u_ViewInfo.x, u.u_ViewInfo.y, u.u_ViewInfo.zw);\n"
"}\n";

