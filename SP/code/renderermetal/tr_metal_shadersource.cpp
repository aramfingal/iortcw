// Placeholder 1×1 white texture — all texels = {1,1,1,1} in BGRA8Unorm.
// Created lazily, released never (lives for renderer lifetime).
// Used until the MTL::Texture side-table from Phase 4 lands.
static MTL::Texture *s_whiteTexture = NULL;

MTL::Texture *GLMetal_GetPlaceholderWhiteTexture(void)
{
    if (s_whiteTexture)
        return s_whiteTexture;

    MTL::Device *device = GLMetal_Device();
    if (!device)
        return NULL;

    MTL::TextureDescriptor *desc = MTL::TextureDescriptor::alloc()->init();
    desc->setTextureType(MTL::TextureType2D);
    desc->setPixelFormat(MTL::PixelFormatRGBA8Unorm);
    desc->setWidth(1);
    desc->setHeight(1);
    desc->setMipmapLevelCount(1);
    desc->setUsage(MTL::TextureUsageShaderRead);
    desc->setStorageMode(MTL::StorageModeShared);

    s_whiteTexture = device->newTexture(desc);
    desc->release();

    if (s_whiteTexture)
    {
        // Fill with white: RGBA = {255,255,255,255}
        uint8_t white[4] = { 255, 255, 255, 255 };
        MTL::Region region = MTL::Region::Make2D(0, 0, 1, 1);
        s_whiteTexture->replaceRegion(region, 0, white, 4);
    }
    return s_whiteTexture;
}

// Default clamp-to-edge, linear filtering sampler.
static MTL::SamplerState *s_defaultSampler = NULL;

MTL::SamplerState *GLMetal_GetDefaultSamplerState(void)
{
    if (s_defaultSampler)
        return s_defaultSampler;

    MTL::Device *device = GLMetal_Device();
    if (!device)
        return NULL;

    MTL::SamplerDescriptor *sdesc = MTL::SamplerDescriptor::alloc()->init();
    sdesc->setMinFilter(MTL::SamplerMinMagFilterLinear);
    sdesc->setMagFilter(MTL::SamplerMinMagFilterLinear);
    sdesc->setSAddressMode(MTL::SamplerAddressModeClampToEdge);
    sdesc->setTAddressMode(MTL::SamplerAddressModeClampToEdge);

    s_defaultSampler = device->newSamplerState(sdesc);
    sdesc->release();
    return s_defaultSampler;
}
