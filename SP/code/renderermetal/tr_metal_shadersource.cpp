"/* ── Helper: camera-space XY base position from integer coordinates ──────────── */\n"
"/* Byte-for-byte identical to Apple ref: AAPLAmbientObscurance.metal:37–53        */\n"
"inline float2 GetCameraSpaceBasePosition(\n"
"    uint2 coordinates,\n"
"    constant MetalSAOFrameParams&  frameData,\n"
"    constant MetalSAOCameraParams& cameraParams)\n"
"{\n"
"    float2 ndc;\n"
"    ndc.xy = (float2(coordinates) + 0.5f) * frameData.invPhysicalSize;\n"
"    ndc.xy = ndc.xy * 2.0f - 1.0f;\n"
"    ndc.y  *= -1.0f;\n"
"\n"
"    float4x4 invProjectionMatrix = cameraParams.invProjectionMatrix;\n"
"    float2 cameraSpacePosition = {\n"
"        ndc.x * invProjectionMatrix.columns[0][0] + invProjectionMatrix.columns[3][0],\n"
"        ndc.y * invProjectionMatrix.columns[1][1] + invProjectionMatrix.columns[3][1],\n"
"    };\n"
"\n"
"    return cameraSpacePosition;\n"
"}\n"
"\n"
"/* ── Helper: camera-space position from base + screen-space offset + depth ───── */\n"
"/* Byte-for-byte identical to Apple ref: AAPLAmbientObscurance.metal:56–73        */\n"
"inline float3 GetOffsetCameraSpacePositionFromDepth(\n"
"    float2 baseInCameraSpace,\n"
"    float2 offsetInScreenSpace,\n"
"    float  depth,\n"
"    constant MetalSAOFrameParams&  frameData,\n"
"    constant MetalSAOCameraParams& cameraParams)\n"
"{\n"
"    float4x4 invProjectionMatrix = cameraParams.invProjectionMatrix;\n"
"    const float2 ndcScale         = float2(2.0f, -2.0f) * frameData.invPhysicalSize;\n"
"    const float2 cameraSpaceScale = ndcScale * float2(invProjectionMatrix.columns[0][0],\n"
"                                                      invProjectionMatrix.columns[1][1]);\n"
"\n"
"    float4 cameraSpacePosition = float4(\n"
"        baseInCameraSpace + offsetInScreenSpace * cameraSpaceScale,\n"
"        1.0f,\n"
"        depth * invProjectionMatrix.columns[2][3] + invProjectionMatrix.columns[3][3]);\n"
"\n"
"    cameraSpacePosition.xyz /= cameraSpacePosition.w;\n"
"\n"
"    return cameraSpacePosition.xyz;\n"
"}\n"
"\n"
"/* ── Helper: rotate a 2D vector by a (cos, sin) pair ────────────────────────── */\n"
"/* Byte-for-byte identical to Apple ref: AAPLAmbientObscurance.metal:76–82        */\n"
"inline float2 RotateVector(float2 v, float2 rotation)\n"
"{\n"
"    float2 vr;\n"
"    vr.x = v.x * rotation.x - v.y * rotation.y;\n"
"    vr.y = v.x * rotation.y + v.y * rotation.x;\n"
"    return vr;\n"
"}\n"
"\n"
"/* ── SAO compute kernel ──────────────────────────────────────────────────────── */\n"
"/*\n"
" * Entry point: scalableAmbientObscurance\n"
" *\n"
" * Adapted from: for-copilot/Renderer/Shaders/AAPLAmbientObscurance.metal:91–178\n"
" * Changes vs. Apple reference:\n"
" *   1. Buffer/texture arguments use our METAL_SAO_* binding index constants (same\n"
" *      numeric values as the Apple sample for texture slots 0–2; buffer slots differ).\n"
" *   2. Struct parameter types are MetalSAOFrameParams / MetalSAOCameraParams in place\n"
" *      of AAPLFrameConstants / AAPLCameraParams (identical memory layout).\n"
" *   3. V1 NO-PYRAMID: tap depth is read from depthMipTexture at full resolution\n"
" *      (mip level 0, coordinate xy unchanged) instead of the hierarchical\n"
" *      `depthMipTexture.read((uint2)(xy >> (mipLevel+1)), mipLevel)` sample.\n"
" *      The mipLevel variable is not computed in v1.\n"
" *\n"
" * Parity deviation ref: code/renderergl2/glsl/ssao_fp.glsl\n"
" */\n"
"kernel void scalableAmbientObscurance(\n"
"    uint2 coordinates                                        [[thread_position_in_grid]],\n"
"    uint2 size                                               [[threads_per_grid]],\n"
"    constant MetalSAOFrameParams&  frameData                 [[buffer(METAL_SAO_BUFFER_FRAME_PARAMS)]],\n"
"    constant MetalSAOCameraParams& cameraParams              [[buffer(METAL_SAO_BUFFER_CAMERA_PARAMS)]],\n"
"    texture2d<float, access::write> image                    [[texture(METAL_SAO_TEXTURE_OUTPUT)]],\n"
"    depth2d<float,   access::read>  depthTexture             [[texture(METAL_SAO_TEXTURE_DEPTH)]],\n"
"    depth2d<float,   access::read>  depthMipTexture          [[texture(METAL_SAO_TEXTURE_DEPTH_MIP)]])\n"
"{\n"
"    const bool temporal      = true;\n"
"    const int  temporalFrames = temporal ? 4 : 1;\n"
"\n"
"    int tapCount = 36 / temporalFrames;\n"
"\n"
"    /* radius in pixels: 1 metre / tan(half-fov), scaled to half-height           */\n"
"    /* Apple ref: AAPLAmbientObscurance.metal:104                                  */\n"
"    const float worldSpaceRadius = 24.0f;\n"
"    const float radius     = worldSpaceRadius * 0.5f * depthTexture.get_height() * cameraParams.projectionMatrix[1][1];\n"
"    const uint  numSpirals = 11;\n"
"    const float bias       = 0.001f;\n"
"    const float epsilon    = 0.01f;\n"
"    const float intensity  = 1.0f;\n"
"\n"
"    /* ── Read centre depth and reconstruct camera-space position ─────────────── */\n"
"    float  depth          = depthTexture.read(coordinates);\n"
"    float3 cameraPosition = GetCameraSpacePositionFromDepth(coordinates, depth, frameData, cameraParams);\n"
"    float2 cameraBasePosition = GetCameraSpaceBasePosition(coordinates, frameData, cameraParams);\n"
"\n"
"    /* ── Normal-from-depth (4 neighbours, shortest gradient wins) ─────────────── */\n"
"    /* Apple ref: AAPLAmbientObscurance.metal:115–130                               */\n"
"    float  depthd = depthTexture.read(coordinates + uint2(0, 1));\n"
"    float  depthr = depthTexture.read(coordinates + uint2(1, 0));\n"
"    float  depthu = depthTexture.read(coordinates - uint2(0, 1));\n"
"    float  depthl = depthTexture.read(coordinates - uint2(1, 0));\n"
"\n"
"    float3 cameraPositiond = GetOffsetCameraSpacePositionFromDepth(cameraBasePosition, float2( 0,  1), depthd, frameData, cameraParams);\n"
"    float3 cameraPositionr = GetOffsetCameraSpacePositionFromDepth(cameraBasePosition, float2( 1,  0), depthr, frameData, cameraParams);\n"
"    float3 cameraPositionu = GetOffsetCameraSpacePositionFromDepth(cameraBasePosition, float2( 0, -1), depthu, frameData, cameraParams);\n"
"    float3 cameraPositionl = GetOffsetCameraSpacePositionFromDepth(cameraBasePosition, float2(-1,  0), depthl, frameData, cameraParams);\n"
"\n"
"    float3 dyu = cameraPositionu - cameraPosition;\n"
"    float3 dyd = cameraPositiond - cameraPosition;\n"
"    float3 dy  = length_squared(dyd) < length_squared(dyu) ? dyd : -dyu;\n"
"    float3 dxr = cameraPositionr - cameraPosition;\n"
"    float3 dxl = cameraPositionl - cameraPosition;\n"
"    float3 dx  = length_squared(dxl) < length_squared(dxr) ? -dxl : dxr;\n"
"    float3 normal = normalize(cross(dx, dy));\n"
"\n"
"    /* ── Temporal dither seed ─────────────────────────────────────────────────── */\n"
"    /* Apple ref: AAPLAmbientObscurance.metal:132–139                               */\n"
"    float sum  = 0.0f;\n"
"    int   taps = 0;\n"
"    uint  seed = ((coordinates.y << 16u) | coordinates.x) * 100u;\n"
"\n"
"    if (temporal)\n"
"        seed += frameData.frameCounter;\n"
"\n"
"    float dither = wang_hash(seed) / float(0xFFFFFFFFu);\n"
"\n"
"    /* ── Spiral tap parameters ────────────────────────────────────────────────── */\n"
"    /* Apple ref: AAPLAmbientObscurance.metal:141–148                               */\n"
"    float  discSize      = radius / cameraPosition.z;\n"
"    float  angleIncrement = (float(numSpirals) * M_PI_F * 2.0f) / float(tapCount);\n"
"    float2 tapRotation   = float2(cos(angleIncrement), sin(angleIncrement));\n"
"\n"
"    float  initialAngle    = dither * M_PI_F * 2.0f;\n"
"    float2 offsetDirection = float2(cos(initialAngle), sin(initialAngle));\n"
"\n"
"    float alpha = dither / float(tapCount);\n"
"\n"
"    /* ── Spiral tap loop ──────────────────────────────────────────────────────── */\n"
"    /* Apple ref: AAPLAmbientObscurance.metal:150–174                               */\n"
"    for (int i = 0; i < tapCount;\n"
"         i++,\n"
"         alpha += 1.0f / float(tapCount),\n"
"         offsetDirection = RotateVector(offsetDirection, tapRotation))\n"
"    {\n"
"        float offsetScale = alpha * alpha;  /* square-bias towards origin */\n"
"\n"
"        float2 offset = floor(offsetDirection * offsetScale * discSize);\n"
"        int2   xy     = (int2)coordinates + (int2)offset;\n"
"\n"
"        if (any(xy < int2(0, 0)) || any(xy >= int2(depthTexture.get_width(), depthTexture.get_height())))\n"
"            continue;\n"
"\n"
"        /*\n"
"         * V1 NO-PYRAMID: read full-resolution depth at mip level 0.\n"
"         * Apple reference reads: depthMipTexture.read((uint2)(xy >> (mipLevel+1)), mipLevel)\n"
"         * That requires a pre-built depth pyramid (AAPLDepthPyramid pattern) — deferred to v2.\n"
"         * In v1 the host binds the same Depth32Float texture to both texture(1) and texture(2).\n"
"         */\n"
"        float depth2 = depthMipTexture.read((uint2)xy, 0);\n"
"        if (depth2 == 1.0f)\n"
"            continue;\n"
"\n"
"        float3 cameraPosition2 = GetOffsetCameraSpacePositionFromDepth(cameraBasePosition, offset, depth2, frameData, cameraParams);\n"
"        float3 v = cameraPosition2 - cameraPosition;\n"
"\n"
"        float vv = dot(v, v);\n"
"        float vn = dot(v, normal);\n"
"        sum += max((vn - bias) / (epsilon + vv), 0.0f);\n"
"        taps++;\n"
"    }\n"
"\n"
"    /* No valid taps: write \"no occlusion\" (1.0) instead of dividing by zero.    */\n"
"    /* taps==0 -> 1.0/taps=+inf -> sum*inf=NaN -> max(0,NaN)=0 -> black multiply. */\n"
"    if (taps == 0) {\n"
"        image.write(float4(1.0f), coordinates);\n"
"        return;\n"
"    }\n"
"\n"
"    /* ── Write AO result ──────────────────────────────────────────────────────── */\n"
"    /* Apple ref: AAPLAmbientObscurance.metal:176–177                               */\n"
"    float x = max(0.0f, 1.0f - sum * intensity * (1.0f / float(taps)));\n"
"    image.write(float4(x), coordinates);\n"
"}\n";

